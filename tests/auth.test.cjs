const assert=require('node:assert/strict');
const {loginEmail,displayIdentifier,validateSignup,authErrorMessage}=require('../lib/auth.cjs');
const input={identifier:' Student_01 ',password:'Test-only-pass123',confirmation:'Test-only-pass123'};
assert.equal(validateSignup(input).email,'student_01@accounts.knupass.invalid');
assert.equal(loginEmail(' Existing@example.com '),'existing@example.com');
assert.equal(displayIdentifier(loginEmail('student_01')),'student_01');
assert.equal(displayIdentifier('existing@example.com'),'existing@example.com');
for(const identifier of ['ab','한글아이디','bad space','a'.repeat(25),'mail@example.com'])assert.throws(()=>validateSignup({...input,identifier}),/아이디/);
assert.throws(()=>validateSignup({...input,confirmation:'different'}),/일치/);
assert.throws(()=>validateSignup({...input,password:'short',confirmation:'short'}),/8자/);
assert.throws(()=>validateSignup({...input,password:'가'.repeat(25),confirmation:'가'.repeat(25)}),/72바이트/);
assert.match(authErrorMessage({code:'user_already_exists'}),/이미 사용/);
assert.match(authErrorMessage({code:'over_request_rate_limit'}),/요청이 많습니다/);
assert.doesNotMatch(authErrorMessage({message:'private upstream error'}),/private upstream/);
console.log('PASS: username normalization, legacy login, validation, password confirmation, safe errors');
