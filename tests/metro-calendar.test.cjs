const assert=require('node:assert/strict');
const {metroCalendar}=require('../server/metro-calendar.cjs');
const day=date=>metroCalendar(Date.parse(`${date}T12:00:00+09:00`)).day;
assert.equal(day('2026-10-20'),'WEEKDAY');
assert.equal(day('2026-10-24'),'SAT');
assert.equal(day('2026-10-25'),'HOLIDAY');
assert.equal(day('2026-10-09'),'HOLIDAY');
assert.equal(day('2026-10-05'),'HOLIDAY');
assert.equal(day('2026-02-16'),'HOLIDAY');
assert.equal(day('2026-02-17'),'HOLIDAY');
assert.equal(day('2026-02-18'),'HOLIDAY');
assert.equal(day('2026-02-19'),'WEEKDAY');
assert.equal(day('2026-09-24'),'HOLIDAY');
assert.equal(day('2026-09-25'),'HOLIDAY');
assert.equal(day('2026-09-26'),'HOLIDAY');
assert.equal(day('2026-06-03'),'HOLIDAY');
assert.equal(day('2026-05-01'),'HOLIDAY');
assert.equal(day('2027-05-03'),'HOLIDAY');
const overnight=metroCalendar(Date.parse('2026-10-10T00:30:00+09:00'));
assert.equal(overnight.serviceDate,'2026-10-09');assert.equal(overnight.day,'HOLIDAY');
